/**
 * When the system drive is nearly full, move Chromium's own caches (Cache / GPUCache / Local Storage ...)
 * to the drive holding the Android data directory.
 * By default these caches live in %APPDATA%\apkstart - with only a few hundred MB left on C:, even starting can fail,
 * even though the user has usually moved Android data elsewhere while the caches still squeeze onto C:.
 * It must be set before app ready; changing it afterwards has no effect.
 */
function relocateUserDataIfCrowded() {
  try {
    const doctor = require('./core/doctor');
    const freeMB = doctor.freeDiskMB(store.DATA_DIR);
    const avd = String(store.getSettings().runtime.avdDir || '').trim();
    if (!avd) return;
    const avdFree = doctor.freeDiskMB(avd);
    if (freeMB >= 2048 || avdFree <= freeMB * 2) return;
    const target = path.join(avd, 'appdata');
    fs.mkdirSync(target, { recursive: true });
    app.setPath('userData', target);
  } catch (_) { /* if it cannot be moved, keep the default; startup is unaffected */ }
}
