/**
 * Rotate = swap the physical panel size and restart the emulator.
 *
 * This is the only way to get an upright, filled landscape screen (all three wrong paths were tried):
 *   - wm size: changes the logical resolution only, the physical LCD stays portrait -> the picture lies 90 degrees over and fills a strip in the top-left;
 *   - wm density: the framebuffer size is unchanged -> the picture does not fill, leaving a large blank area on the right after maximising;
 *   - adb emu rotate: rotates the picture content only, and the system stays portrait.
 * Only swapping hw.lcd.width/height for landscape and restarting makes Qt open a landscape-panel window with an upright, filled picture.
 */
async function restartForOrientation(landscape) {
  if (!appWin || !appWin.isOpen) return false;
  const pkg = appWin.pkg;
  store.saveSettings({ display: { landscape: !!landscape } });
  send('runtime:log', landscape ? 'Switching to landscape: restarting the Android runtime…' : 'Switching back to portrait: restarting the Android runtime…');
  try {
    // Detach the embedded window first so no black window is left on the desktop during the restart
    try { await appWin.agent.detach(); } catch (_) { /* ignore */ }
    await runtime.stop({ graceful: false }).catch(() => {});
    appLog(`rotate -> landscape=${landscape} restarting runtime`);
    const rt = await runtime.ensure({
      onLog: (m) => { send('runtime:log', m); appLog(`  rt ${m}`); },
    });
    if (!rt || !rt.ok) return false;
    await runtime.waitForNetwork({ onLog: () => {}, timeoutMs: 25000 }).catch(() => null);
    if (pkg) {
      const app = store.getApp(pkg);
      if (app) {
        await rt.client.install(app.apkPath).catch(() => {});
        await rt.client.startApp(app.package, app.activity, {}).catch(() => {});
      }
    }
    await new Promise((r) => setTimeout(r, 1500));
    const embedded = await appWin.embed().catch(() => false);
    if (!embedded) {
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 1500);
      setTimeout(() => { if (appWin.isOpen) appWin.embed().catch(() => {}); }, 4000);
    }
    appWin.scheduleFit(6);
    return true;
  } catch (e) {
    appLog(`rotate restart failed: ${e && e.message}`);
    return false;
  }
}

/** Open (or reuse) the "one clean window per app" */
function openAppWindow(pkg, tip) {
  const rec = store.getApp(pkg);
  const land = !!displaySettings().landscape;
  const p0 = portraitSize();
  appWin.open({
    pkg,
    label: (rec && rec.label) || pkg,
    iconPath: rec && rec.icoPath,
    // In landscape the window opens at a landscape ratio, or a portrait window with a landscape picture leaves large black bars
    portrait: land ? { w: p0.h, h: p0.w } : p0,
    fullscreen: displaySettings().mode === 'fullscreen',
  });
  appWin.setIcon(rec && rec.icoPath);
  // Initialise from the saved orientation (the physical panel orientation is decided in doctor.lcdFor)
  appWin.setState({
    tip: tip || 'Starting the Android runtime…',
    ready: false,
    landscape: !!displaySettings().landscape,
  });
  currentAppPkg = pkg;
}

async function toggleDisplayMode() {
  const next = store.saveSettings({
    display: { mode: displaySettings().mode === 'fullscreen' ? 'window' : 'fullscreen' },
  });
  const full = next.display.mode === 'fullscreen';
  if (appWin && appWin.isOpen) {
    if (full) appWin.win.maximize();
    else appWin.win.unmaximize();
    appWin.scheduleFit(6);
    // Full screen = landscape: change the physical panel and restart the runtime, or the portrait picture is merely enlarged with a large blank on the right
    if (!!displaySettings().landscape !== full) {
      appWin.rotate(restartForOrientation).catch(() => {});
    }
  }
  return next.display.mode;
}

/** Install adb / emulator / system images in one go on first run, no longer in 1-5 steps */
let deploying = false;
async function autoDeploy({ force = false } = {}) {
  if (deploying || !store.getSettings().autoDeploy) return { ok: false, error: 'skipped' };
  // Download failure cooldown: previously, whenever checkEnv() still missed components, every ApkStart start re-pulled
  // the 1.5GB runtime package, which users saw as "downloading over and over".
  // A timestamp is recorded on failure and no automatic retry happens for 30 minutes; a manual "one-click setup"
  // passes force=true to retry at once. Success or a forced attempt clears the cooldown.
  const COOLDOWN_MS = 30 * 60 * 1000;
  const lastFail = Number(store.getSettings().runtime.deployFailedAt || 0);
  if (!force && lastFail && Date.now() - lastFail < COOLDOWN_MS) {
    appLog(`autoDeploy cooling down (last failure at ${new Date(lastFail).toISOString()}), skipping automatic retry`);
    return { ok: false, error: 'cooldown', cooldown: true, until: lastFail + COOLDOWN_MS };
  }
  deploying = true;
  const progress = (p) => send('provision:progress', { ...p, component: p.component || 'all' });
  let succeeded = false;
  try {
    const env = await runtime.provisioner.checkEnv();
    const needEngine = !env.emulator.ok || !env.sysimg.ok;
    // The slim edition prefers this project's GitHub runtime bundle: one file covers the emulator + system images,
    // with download and update sources unified on GitHub (far more reliable than dl.google.com in mainland China).
    // If the bundle is unavailable (no network / asset not published yet / rate limited), install piecewise from official sources.
    if (needEngine && store.getSettings().runtime.preferGithubRuntime !== false) {
      try {
        progress({ message: 'Downloading the runtime from GitHub…' });
        await runtime.provisioner.installRuntimePack(progress);
        const afterPack = await runtime.provisioner.checkEnv();
        if (afterPack.emulator.ok && afterPack.sysimg.ok) {
          succeeded = true;
          return { ok: true, source: 'github' };
        }
        progress({ message: 'The runtime pack is incomplete; filling in from the official sources…' });
      } catch (e) {
        progress({ message: `GitHub runtime unavailable (${e.message}); using the official sources…` });
      }
    }
    if (!env.adb.ok) {
      progress({ message: 'Preparing adb…' });
      await runtime.provisioner.installAdb(progress);
    }
    if (!env.emulator.ok) {
      progress({ message: 'Preparing the Android runtime…' });
      await runtime.provisioner.installEmulator(progress);
    }
    if (!env.sysimg.ok) {
      progress({ message: 'Preparing the Android system image…' });
      await runtime.provisioner.installSystemImage(progress);
    }
    const after = await runtime.provisioner.checkEnv();
    succeeded = !!(after.adb.ok && after.emulator.ok && after.sysimg.ok);
    return { ok: succeeded };
  } catch (e) {
    return { ok: false, error: e.message };
  } finally {
    // Only a real failure starts the cooldown; a successful setup clears the old failure record.
    try {
      store.saveSettings({ runtime: { deployFailedAt: succeeded ? 0 : Date.now() } });
    } catch (_) { /* an unwritable setting does not change this result */ }
    deploying = false;
  }
}

