// ---------------- lifecycle ----------------

const gotLock = app.requestSingleInstanceLock();
if (!gotLock) {
  app.quit();
} else {
  app.on('second-instance', (_evt, argv) => {
    const args = parseArgs(argv);
    if (args.launch) { runLaunch(args.launch); return; }
    if (args.apk) { runInstall(args.apk).catch(() => {}); return; }
    showWindow();
  });

  app.whenReady().then(async () => {
    store.ensureDirs();
    runtime = new Runtime(APP_ROOT);
    // Leave a trace at startup: an app.log sent in on a problem shows the version and data directory
    appLog(`start v${app.getVersion()} data=${store.DATA_DIR} pid=${process.pid}`);
    const l = launcherInfo();
    installer = new Installer(runtime, {
      launcherTarget: l.target,
      launcherArgs: l.args,
      cwd: l.cwd,
      isDev: IS_DEV,
      desktopDir: app.getPath('desktop'),
      // Windows Search indexes .lnk files in the Start menu; a desktop-only shortcut makes the app unfindable
      startMenuDir: path.join(app.getPath('appData'), 'Microsoft', 'Windows', 'Start Menu', 'Programs'),
      decodeIcon,
    });
    sharer = new Sharer(runtime);
    androidSet = new AndroidSettings(runtime);

    updater = new Updater({
      currentVersion: app.getVersion(),
      exePath: process.execPath,
      isPackaged: app.isPackaged,
      dataDir: store.DATA_DIR,
      // Lets the updater read "GitHub only / Gitee only / auto fastest" and the mirror prefix setting
      settings: () => store.getSettings(),
      onProgress: (p) => send('update:progress', p),
    });

    // Wheel coalescer: scrolls within one time window inject a single input swipe over a resident adb shell.
    wheelRouter = new pointer.WheelRouter({
      getSize: getDeviceSize,
      inject: (cmd) => runtime.client().input(cmd),
    });

    // Window agent: handles only the embedded emulator window. The global mouse hook is installed per config only while an app window is in the foreground.
    winAgent = new WinAgent();
    appWin = new AppWindow({
      agent: winAgent,
      // Rotation changes Android's logical resolution, so hand it to the adb client
      setOrientation: async (landscape) => {
        deviceSize.value = null;
        return runtime.client().setOrientation(landscape);
      },
      // Pass a getter: binding changes in settings apply on the next window focus / refresh, with no restart
      pointerConfig: () => pointer.pointerOptions(store.getSettings()),
    });
    appWin.onCloseApp((pkg) => {
      // Closing a window stops that app; closing the last one parks the container (lower priority, stop polling),
      // while Android itself stays, so the next tap is instant instead of a cold boot.
      runtime?.endApp(pkg, { onIdle: onContainerActive }).catch(() => {});
    });

    // "Which windows are ours" = the runtime directory + the bundled engine directory.
    // The window agent may only touch windows created by these processes - other Qt apps (WeChat 4.x is Qt6,
    // with the same window class names as the emulator) must never be touched; see SetScope in agent.ps1.
    const agentScope = () => {
      const dirs = [];
      try { dirs.push(runtime.provisioner.root); } catch (_) { /* ignore */ }
      try { dirs.push(path.join(APP_ROOT, 'engine')); } catch (_) { /* ignore */ }
      return dirs.filter(Boolean);
    };
    // The scope lives in the agent process's memory and is lost when it is rebuilt, so resend it before suppression starts.
    armAgent = async (agent) => {
      if (!agent) return { ok: false };
      const dirs = agentScope();
      // The second argument is this process's pid: the agent refuses to embed windows into ones that are not ours
      await agent.scope(dirs, process.pid).catch(() => null);
      if (!dirs.length) appLog('Agent scope is empty: no windows are suppressed (avoids affecting other software)');
      return agent.bootHide().catch(() => ({ ok: false }));
    };

    // A rebuilt agent process after an unexpected exit needs the event listeners reattached too (the old version lost
    // right-click back and the wheel here, showing as "it stops responding after a while").
    const attachAgentEvents = (agent) => {
      agent.on('back', () => { runtime.client().keyBack().catch(() => {}); });
      agent.on('forward', () => { runtime.client().keyForward().catch(() => {}); });
      agent.on('wheel', (m) => {
        if (pointer.pointerOptions(store.getSettings()).wheel === 'smooth') wheelRouter.push(m);
      });
      agent.on('exit', () => {
        const next = new WinAgent();
        winAgent = next;
        appWin.agent = next;
        attachAgentEvents(next);
        // A new agent has no scope info and will not touch any window until this is resent
        armAgent(next).catch(() => {});
      });
    };
    attachAgentEvents(winAgent);

    // The gate for console-window suppression must open before the emulator process is created.
    // The old implementation hid it 4 seconds after ApkStart started, but the emulator had already created
    // the qemu console window by then - a black frame flashing past.
    runtime.emulator.onBeforeSpawn = async () => {
      if (!winAgent) return;
      await armAgent(winAgent);
    };
    // The window agent is a resident PowerShell process with a cold start of about 300-600ms.
    // Start it early instead of waiting when a window actually needs hiding.
    winAgent.ensure().then(() => armAgent(winAgent)).catch(() => {});

    registerIpc();
    createWindow({ show: !parseArgs(process.argv).silent });
    buildTray();
    applyAutoStart();

    // Free disk: below 3GB Android cannot start at all (writing the image/snapshot fails).
    // Rather than leaving the user with an unexplained "cannot open", say up front where to change it.
    {
      const doctor = require('./core/doctor');
      const freeMB = doctor.freeDiskMB(store.DATA_DIR);
      if (freeMB && freeMB < 3072) {
        appLog(`LOW_DISK free=${freeMB}MB dir=${store.DATA_DIR}`);
        setTimeout(() => {
          notify('Not enough disk space', `Only ${(freeMB / 1024).toFixed(1)} GB left. Move the Android data / runtime folders to another drive in "Settings → System integration", or free up disk space.`);
          send('toast', { type: 'error', message: `Only ${(freeMB / 1024).toFixed(1)} GB left on disk; Android may fail to start (change drives in Settings → System integration)` });
        }, 3000).unref?.();
      }
    }

    // Old versions created only a desktop shortcut / a null icon: fill it in at startup with no user action
    installer.ensureShortcuts().then((fixed) => {
      if (fixed && fixed.length) {
        windowctl.refreshShell().catch(() => {});
        notify('Shortcuts restored', fixed.join(', '));
      }
    }).catch(() => {});

    // F11 full screen / window switching; global shortcuts work only while ApkStart is alive
    try {
      globalShortcut.register('F11', () => { toggleDisplayMode(); });
    } catch (_) { /* ignore */ }

    const args = parseArgs(process.argv);
    if (args.apk) runInstall(args.apk).catch(() => {});
    else if (args.launch) await runLaunch(args.launch);

    // Prewarm: keep the Android environment resident, as WSA / Tencent's PC store do.
    // ApkStart boots it in the background on open (window hidden throughout), so a later tap is just one am start.
    // Prewarm only when apps are installed and a runtime is available, so first use / pure management does not waste memory.
    const prewarmEnabled = store.getSettings().engine.prewarm !== false;
    if (prewarmEnabled && !args.launch && store.getApps().length > 0) {
      // 1.2 seconds is enough for the first frame. It used to wait 4 seconds, by which time the user had already tapped an app,
      // so "open" and "prewarm" fought over the same AVD lock and it was slower.
      setTimeout(async () => {
        try {
          const env = await runtime.provisioner.checkEnv();
          if (!(env.adb.ok && env.emulator.ok && env.sysimg.ok)) {
            appLog(`prewarm skipped: not ready (adb=${env.adb.ok} emu=${env.emulator.ok} img=${env.sysimg.ok})`);
            return;
          }
          // Hide the emulator window and qemu console during boot; the user should see no window at all
          // Note the await: spawning before it applies always shows the black window.
          if (winAgent) { try { await armAgent(winAgent); } catch (_) { /* ignore */ } }
          const t0 = Date.now();
          appLog('prewarm start');
          const r = await runtime.prewarm({ onLog: (m) => appLog(`prewarm ${m}`) });
          if (r && r.ok) appLog(`prewarm ready in ${Date.now() - t0}ms`);
          else {
            appLog(`prewarm failed: ${r && (r.error || r.skipped)}`);
            // Keep suppressing the emulator window even after a failed prewarm: it may just be slow and come up later,
            // and the user should never see an emulator on the desktop because prewarm "failed".
            if (winAgent) armAgent(winAgent).catch(() => {});
          }
        } catch (e) { appLog(`prewarm error: ${e && e.message}`); /* a failed prewarm does not affect opening apps later */ }
      }, 1200).unref?.();
    } else {
      appLog(`prewarm off (enabled=${prewarmEnabled} launch=${!!args.launch} apps=${store.getApps().length})`);
    }

    // Defer first-run component setup by 20 seconds: disk/CPU are already saturated during the cold start,
    // and concurrent downloading/extracting only makes the desktop lag. When an app really needs to open, ensure() prepares it anyway.
    setTimeout(() => {
      autoDeploy().then((r) => {
        if (r && r.ok) send('toast', { type: 'ok', message: 'Runtime prepared automatically' });
      }).catch(() => {});
    }, 20000).unref?.();

    // Silently check for a new version 8 seconds after start (meaningful only when packaged). A new version is only surfaced,
    // never downloaded automatically - updating is what "update now" does.
    if (app.isPackaged) {
      setTimeout(() => {
        updater.check().then((info) => {
          updateInfo = info;
          send('update:state', info);
          if (info.hasUpdate) {
            appLog(`update available ${info.tag} (current v${app.getVersion()}, asset=${info.asset ? info.asset.name : 'none'})`);
            // No separate system notification any more: startup prompts go into the in-app welcome card,
            // avoiding another corner bubble at autostart (one of the reported "little popups").
          }
        }).catch((e) => appLog(`update check failed: ${e.message}`));
      }, 8000).unref?.();
    }

    // File sync / notification polling no longer run unconditionally: they run only while the container has a real app window
    // (see onContainerActive).

    // Smoke test: exit after a screenshot, used to verify automatically that the UI renders
    if (process.argv.includes('--smoke') && mainWindow) {
      const out = process.argv[process.argv.indexOf('--smoke') + 1] || 'smoke.png';
      mainWindow.webContents.once('did-finish-load', () => {
        setTimeout(async () => {
          try {
            if (process.argv.includes('--setup')) {
              // The runtime panel is merged into settings: --setup equals --settings, so screenshot the settings page directly
              await mainWindow.webContents.executeJavaScript(
                "document.getElementById('btnSettings').click(); true;",
              );
              await new Promise((r) => setTimeout(r, 2500));
            }
            if (process.argv.includes('--settings')) {
              const opened = await mainWindow.webContents.executeJavaScript(`
                (async () => {
                  document.getElementById('btnSettings').click();
                  for (let i = 0; i < 50; i++) {
                    await new Promise((r) => setTimeout(r, 100));
                    if (document.getElementById('settingsMask').classList.contains('on')) return true;
                  }
                  return false;
                })()
              `);
              console.log('[smoke] settings opened =', opened);
              await new Promise((r) => setTimeout(r, 600));
              const dbg = await mainWindow.webContents.executeJavaScript(
                "JSON.stringify({ on: document.getElementById('settingsMask').classList.contains('on'), qr: !!document.querySelector('#aboutGroup img'), qrH: (document.querySelector('#aboutGroup img')||{}).naturalHeight, ver: (document.getElementById('aboutVer')||{}).textContent, note: (document.getElementById('setupNote')||{}).textContent })",
              );
              console.log('[smoke] dom =', dbg);
            }
            // An occluded window can yield a stale frame: force a repaint and take two shots, keeping the second
            const snap = async (file) => {
              mainWindow.webContents.invalidate();
              await mainWindow.webContents.capturePage().catch(() => null);
              await new Promise((r) => setTimeout(r, 400));
              const im = await mainWindow.webContents.capturePage();
              fs.writeFileSync(file, im.toPNG());
              console.log('[smoke] saved', file);
            };
            await snap(out);
            if (process.argv.includes('--perf')) {
              // Capture the "performance and resource usage" area (the control-heaviest block on the settings page)
              await mainWindow.webContents.executeJavaScript(
                "document.getElementById('perfGroup').scrollIntoView({ block: 'start' }); true;",
              );
              await snap(out.replace(/\.png$/i, '-perf.png'));
            }
            if (process.argv.includes('--download')) {
              // Capture the "download and update sources" area
              await mainWindow.webContents.executeJavaScript(
                "document.getElementById('downloadGroup').scrollIntoView({ block: 'start' }); true;",
              );
              await snap(out.replace(/\.png$/i, '-download.png'));
            }
            if (process.argv.includes('--settings')) {
              // Then capture the "about" area (QR code / GitHub / Powered by)
              await mainWindow.webContents.executeJavaScript(
                "document.getElementById('aboutGroup').scrollIntoView({ block: 'center' }); true;",
              );
              await snap(out.replace(/\.png$/i, '-about.png'));
            }
          } catch (e) {
            console.error('[smoke] screenshot failed', e);
          }
          quitting = true;
          app.quit();
        }, 6500);
      });
    }

    app.on('activate', () => showWindow());
  });

  app.on('window-all-closed', () => {
    // Closing the window normally only hides it to the tray (the close event is intercepted),
    // so reaching here means a real exit that must be allowed, or the process lingers holding the single-instance lock.
    if (quitting) app.exit(0);
  });

  let quitReady = false;
  app.on('before-quit', (e) => {
    quitting = true;
    // Before exiting, the window agent must detach and hide the emulator window. That step is asynchronous
    // (it waits for the agent's reply), so the first before-quit is intercepted and the real exit follows teardown.
    // Without this, destroying the host window makes Windows reparent the emulator child window to the desktop and show it -
    // showing as "after closing ApkStart a black Android Emulator window is left on the desktop".
    if (!quitReady) {
      e.preventDefault();
      quitReady = true;
      sharer?.stop();
      notifier?.stop();
      try { appWin?.close({ keepApp: true }); } catch (_) { /* ignore */ }
      const finish = () => {
        try { winAgent?.dispose(); } catch (_) { /* ignore */ }
        try { wheelRouter?.dispose(); } catch (_) { /* ignore */ }
        runtime?.dispose();
        // The hidden icon-decoding window counts as a window too; leaving it open stops window-all-closed from ever firing
        try { if (decodeWindow && !decodeWindow.isDestroyed()) decodeWindow.destroy(); } catch (_) { /* ignore */ }
        app.quit();
      };
      setTimeout(finish, 400);
      return;
    }
    try { winAgent?.dispose(); } catch (_) { /* ignore */ }
    try { wheelRouter?.dispose(); } catch (_) { /* ignore */ }
    runtime?.dispose();
    try { if (decodeWindow && !decodeWindow.isDestroyed()) decodeWindow.destroy(); } catch (_) { /* ignore */ }
  });
}
