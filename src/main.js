/**
 * Automatic takeover by the full edition (bundled runtime):
 * In the release package, runtime/ sits next to ApkStart.exe (emulator + platform-tools + AEHD + ARM compatibility image).
 * On first start (no settings.json yet) runtime.dir is pointed at it and compatibility mode enabled,
 * so users download and configure nothing: it works out of the box. They can still switch back to the online edition in settings.
 */
function bootstrapBundledRuntime() {
  try {
    const exeDir = path.dirname(process.execPath);
    // The portable build keeps the runtime next to the exe; electron-builder's portable target unpacks resources to
    // resources/, with the process exe beside resources, so check several candidate locations.
    const candidates = [
      path.join(exeDir, 'runtime'),
      path.join(path.dirname(exeDir), 'runtime'),
      path.join(process.resourcesPath || '', 'runtime'),
      path.join(process.resourcesPath || '', 'app', 'runtime'),
    ];
    // A bundled runtime only needs "an emulator + some complete system image"; the API version is not hardcoded:
    // the single-file edition may carry a smaller AOSP image, and hardcoding API34 would misjudge it as having no runtime.
    const hasImage = (dir) => {
      const root = path.join(dir, 'system-images');
      let apis = [];
      try { apis = fs.readdirSync(root); } catch (_) { return false; }
      for (const api of apis) {
        let tags = [];
        try { tags = fs.readdirSync(path.join(root, api)); } catch (_) { continue; }
        for (const tag of tags) {
          let abis = [];
          try { abis = fs.readdirSync(path.join(root, api, tag)); } catch (_) { continue; }
          for (const abi of abis) {
            const d = path.join(root, api, tag, abi);
            // In the single-file edition the image is stored compressed (system.img.xz / .gz) and expanded on first start.
            // Accepting only system.img would judge "the package does carry an image" as missing and go online to download.
            const hasSys = ['system.img', 'system.img.xz', 'system.img.gz']
              .some((f) => fs.existsSync(path.join(d, f)));
            if (hasSys && fs.existsSync(path.join(d, 'kernel-ranchu'))) return true;
          }
        }
      }
      return false;
    };
    const bundled = candidates.find((dir) =>
      fs.existsSync(path.join(dir, 'emulator', 'emulator.exe')) && hasImage(dir));
    if (!bundled) return;

    const s = store.getSettings();
    // The old version took over only when settings.json was absent: a user who installed the online edition then unpacked the full one
    // kept getting the "components missing" setup wizard. Now it takes over whenever the current runtime directory has no emulator.
    const explicit = String(s.runtime.dir || '').trim();
    const current = explicit || path.join(store.DATA_DIR, 'runtime');
    const currentExe = path.join(current, 'emulator', 'emulator.exe');
    // After the portable build is moved/upgraded (unpacked into a new directory), settings still records the old path:
    // only runtime/ under this EXE's directory counts, or components from the old package keep being used
    // (measured: the old package's emulator lacked emulator-check -> acceleration probe failed -> fell back to TCG software emulation).
    const sameTree = path.resolve(current).toLowerCase()
      .startsWith(path.resolve(exeDir).toLowerCase());
    const currentOk = fs.existsSync(currentExe) && sameTree;
    // A directory the user picked (outside the EXE tree, e.g. D:\ApkStartRuntime or another drive)
    // is always respected: it may be to save C: space or to share one runtime across portable builds.
    // The old version overwrote it unconditionally with the bundled runtime next to the exe, producing
    // "changed the runtime data directory in settings, yet it still downloads to the old directory / AppData" (issue #23).
    if (explicit && !sameTree && fs.existsSync(currentExe)) {
      if (s.engine.gpuMode === 'swiftshader_indirect' || s.engine.memoryMB === 4096) {
        store.saveSettings({ engine: { gpuMode: 'auto', autoMemory: true, memoryMB: 0, cores: 0 } });
      }
      return;
    }
    // An existing usable runtime (including the online edition) is respected: the AVD user data lives there and must not be moved silently
    if (currentOk) {
      // but auto tuning is still enabled, since hardcoded 4G/4-core/deprecated GPU modes in old configs must not persist
      if (s.engine.gpuMode === 'swiftshader_indirect' || s.engine.memoryMB === 4096) {
        store.saveSettings({ engine: { gpuMode: 'auto', autoMemory: true, memoryMB: 0, cores: 0 } });
      }
      return;
    }
    // Compatibility mode is enabled only when the package carries a Google Play image; AOSP images ship native x86_64 libraries
    let playBundled = false;
    try {
      const root = path.join(bundled, 'system-images');
      for (const api of fs.readdirSync(root)) {
        for (const tag of fs.readdirSync(path.join(root, api))) {
          if (/playstore|google_apis/i.test(tag)) playBundled = true;
        }
      }
    } catch (_) { /* ignore */ }
    store.saveSettings({
      runtime: { dir: bundled, compatImage: playBundled },
      engine: { gpuMode: 'auto', autoMemory: true },
    });
  } catch (_) { /* a failed takeover does not block startup: fall through to the online bootstrap */ }
}
